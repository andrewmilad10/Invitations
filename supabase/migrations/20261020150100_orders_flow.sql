-- ═══════════════════════════════════════════════════════════════════════════
-- 0018 · Orders like a shop: the couple orders, staff confirm payment, the
-- invitation goes live.
--
--   Publish (couple) → order #1001 "Payment pending" + confirmation code
--   Mark as paid (staff) → "Paid", invitation live for 3 months
--   Cancel / refund / archive, tags, and a timeline with staff comments.
--
-- An invitation can only go live after payment: a couple can publish only
-- while the invitation has a paid order and its live period hasn't ended
-- (a trigger checks every client update; staff functions are exempt).
-- Existing published invitations stay as they are.
--
-- Couples read their own orders (a few columns only) and use three
-- functions: request_publish, my_publish_state, cancel_my_order. Staff use
-- admin_* functions that check the role first, as in 0014.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── Orders: number, confirmation, customer, tags, archive, timeline ─────────
alter table public.orders
  add column number         bigint generated by default as identity (start with 1001),
  add column confirmation   text not null default upper(substr(md5(gen_random_uuid()::text), 1, 10)),
  add column customer_name  text check (customer_name is null or char_length(customer_name) <= 120),
  add column customer_phone text check (customer_phone is null or customer_phone ~ '^\+?[0-9]{8,15}$'),
  add column kind           text not null default 'new' check (kind in ('new', 'renewal')),
  add column source         text not null default 'staff' check (source in ('customer', 'staff', 'paymob')),
  add column tags           text[] not null default '{}' check (cardinality(tags) <= 10),
  add column cancelled_at   timestamptz,
  add column cancel_reason  text check (cancel_reason is null or char_length(cancel_reason) <= 300),
  add column archived_at    timestamptz;

-- A pending order has not been paid yet.
alter table public.orders alter column paid_at drop not null, alter column paid_at drop default;
alter table public.orders add constraint orders_paid_at_matches_status
  check ((status in ('paid', 'refunded')) = (paid_at is not null));

create unique index orders_number_key on public.orders (number);
create unique index orders_confirmation_key on public.orders (confirmation);
-- One open order per invitation: ordering twice returns the same order.
create unique index orders_one_pending_per_wedding on public.orders (wedding_id) where status = 'pending';
create index orders_created_at_idx on public.orders (created_at desc);
create index orders_search_trgm_idx on public.orders
  using gin ((lower(coalesce(customer_name, '') || ' ' || coalesce(customer_phone, '') || ' ' || coalesce(reference, ''))) extensions.gin_trgm_ops);

create table public.order_events (
  id       bigint generated always as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  at       timestamptz not null default now(),
  actor    uuid references auth.users (id) on delete set null,
  kind     text not null check (kind in ('placed', 'confirmation', 'paid', 'live', 'cancelled', 'refunded', 'archived', 'unarchived', 'comment')),
  message  text not null check (char_length(message) between 1 and 1000)
);
create index order_events_order_idx on public.order_events (order_id, at desc);
create index order_events_actor_idx on public.order_events (actor);
alter table public.order_events enable row level security;
revoke all on public.order_events from anon, authenticated;
create policy order_events_closed on public.order_events as restrictive for all to anon, authenticated using (false) with check (false);

-- Couples see only these columns of their own orders (never staff notes or tags).
revoke select on public.orders from authenticated;
grant select (id, number, confirmation, wedding_id, amount, currency, method, months, status, kind, created_at, paid_at, refunded_at, cancelled_at)
  on public.orders to authenticated;

-- ── Small helpers (not callable by clients) ────────────────────────────────
create function private.order_price() returns numeric language sql immutable set search_path = '' as $$ select 1000::numeric $$;
create function private.order_months() returns integer language sql immutable set search_path = '' as $$ select 3 $$;

create function private.method_label(p_method text) returns text language sql immutable set search_path = '' as $$
  select case p_method
    when 'instapay' then 'InstaPay' when 'vodafone_cash' then 'Vodafone Cash' when 'bank_transfer' then 'bank transfer'
    when 'cash' then 'cash' when 'card' then 'card' when 'paymob' then 'Paymob' else 'another method' end;
$$;

create function private.money(p_amount numeric, p_currency text) returns text language sql immutable set search_path = '' as $$
  select coalesce(p_currency, 'EGP') || ' ' ||
         case when p_amount = trunc(p_amount) then to_char(p_amount, 'FM999,999,990') else to_char(p_amount, 'FM999,999,990.00') end;
$$;

create function private.order_event(p_order uuid, p_kind text, p_message text)
returns void language sql volatile security definer set search_path = '' as $$
  insert into public.order_events (order_id, actor, kind, message) values (p_order, (select auth.uid()), p_kind, left(p_message, 1000));
$$;

create function private.order_brief(o public.orders) returns jsonb language sql stable set search_path = '' as $$
  select jsonb_build_object(
    'id', o.id, 'number', o.number, 'confirmation', o.confirmation, 'status', o.status,
    'amount', o.amount, 'currency', o.currency, 'method', o.method, 'months', o.months,
    'kind', o.kind, 'createdAt', o.created_at, 'paidAt', o.paid_at);
$$;

-- Live-able right now: not turned off, has a paid order, period not over.
create function private.wedding_can_go_live(p_wedding uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select private.can_edit_wedding(p_wedding) and exists (
    select 1 from public.weddings w
     where w.id = p_wedding
       and w.deactivated_at is null
       and (w.active_until is null or w.active_until > now())
       and exists (select 1 from public.orders o where o.wedding_id = w.id and o.status = 'paid'));
$$;

-- ── Publishing waits for payment ───────────────────────────────────────────
-- SECURITY INVOKER on purpose: current_user is the caller's role, so updates
-- from couples (authenticated) are checked and staff functions (which run as
-- the owner) are not.
create function private.guard_publish() returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  if new.status = 'published' and old.status is distinct from 'published'
     and current_user in ('authenticated', 'anon')
     and not private.wedding_can_go_live(new.id) then
    raise exception 'Payment is needed before this invitation can go live.' using errcode = 'P0402';
  end if;
  return new;
end;
$$;
create trigger weddings_guard_publish before update of status on public.weddings
  for each row execute function private.guard_publish();

-- ── Settling an order (shared by "Mark as paid" and "Record sale") ─────────
create function private.settle_order(p_order uuid, p_amount numeric, p_method text, p_reference text, p_note text, p_publish boolean)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_o public.orders;
  v_w public.weddings;
  v_until timestamptz;
begin
  select * into v_o from public.orders where id = p_order for update;
  if v_o.id is null then
    return jsonb_build_object('ok', false, 'error', 'This order no longer exists.');
  end if;
  if v_o.status <> 'pending' then
    return jsonb_build_object('ok', false, 'error', 'Only orders waiting for payment can be marked as paid.');
  end if;
  if p_amount is not null and (p_amount < 0 or p_amount > 1000000) then
    return jsonb_build_object('ok', false, 'error', 'Enter an amount between 0 and 1,000,000.');
  end if;

  update public.orders
     set status = 'paid', paid_at = now(),
         amount = coalesce(round(p_amount, 2), amount),
         method = coalesce(p_method, method),
         reference = coalesce(nullif(btrim(p_reference), ''), reference),
         note = coalesce(nullif(btrim(p_note), ''), note)
   where id = p_order
   returning * into v_o;

  perform private.order_event(v_o.id, 'paid',
    private.money(v_o.amount, v_o.currency) || ' received by ' || private.method_label(v_o.method)
    || coalesce(' (reference ' || v_o.reference || ')', '') || '.');

  if v_o.wedding_id is not null then
    select * into v_w from public.weddings where id = v_o.wedding_id for update;
    v_until := greatest(coalesce(v_w.active_until, now()), now()) + make_interval(months => v_o.months);
    update public.weddings
       set active_until = v_until,
           status = case when p_publish then 'published'::public.wedding_status else status end
     where id = v_w.id;
    perform private.order_event(v_o.id, 'live',
      case
        when v_w.deactivated_at is not null then 'Paid, but the invitation is turned off. Turn it on from Invitations to show it.'
        when p_publish then 'The invitation is live until ' || to_char(v_until at time zone 'Africa/Cairo', 'FMDD Mon YYYY') || '.'
        else 'Paid until ' || to_char(v_until at time zone 'Africa/Cairo', 'FMDD Mon YYYY') || '. The couple publishes it when ready.'
      end);
  end if;

  return jsonb_build_object('ok', true, 'orderId', v_o.id, 'activeUntil', v_until);
end;
$$;

-- ── Couples ────────────────────────────────────────────────────────────────
create function private.request_publish(p_wedding uuid, p_phone text, p_method text)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_uid   uuid := (select auth.uid());
  v_w     public.weddings;
  v_o     public.orders;
  v_phone text := regexp_replace(btrim(coalesce(p_phone, '')), '[\s\-().]', '', 'g');
begin
  if v_uid is null then
    raise exception 'not signed in' using errcode = '42501';
  end if;
  select * into v_w from public.weddings where id = p_wedding for update;
  if v_w.id is null or not private.can_edit_wedding(v_w.id) then
    return jsonb_build_object('ok', false, 'error', 'Invitation not found.');
  end if;
  if v_w.deactivated_at is not null then
    return jsonb_build_object('ok', false, 'error', 'This invitation is turned off. Please contact us on WhatsApp.');
  end if;
  if private.wedding_can_go_live(v_w.id) then
    return jsonb_build_object('ok', true, 'paid', true);
  end if;

  select * into v_o from public.orders where wedding_id = v_w.id and status = 'pending';
  if v_o.id is not null then
    return jsonb_build_object('ok', true, 'paid', false, 'order', private.order_brief(v_o));
  end if;

  if v_phone !~ '^\+?[0-9]{8,15}$' then
    return jsonb_build_object('ok', false, 'error', 'Please enter a WhatsApp number we can reach you on.');
  end if;
  if p_method is null or p_method not in ('instapay', 'vodafone_cash', 'bank_transfer', 'other') then
    return jsonb_build_object('ok', false, 'error', 'Please choose how you''ll pay.');
  end if;
  if (select count(*) from public.orders where buyer_id = v_uid and status = 'pending') >= 5 then
    return jsonb_build_object('ok', false, 'error', 'You have several orders waiting for payment. Please pay or cancel one first.');
  end if;

  insert into public.orders (wedding_id, buyer_id, amount, method, months, status, customer_name, customer_phone, kind, source, created_by)
  values (
    v_w.id, v_uid, private.order_price(), p_method, private.order_months(), 'pending',
    (select p.full_name from public.profiles p where p.id = v_uid), v_phone,
    case when exists (select 1 from public.orders o where o.wedding_id = v_w.id and o.status in ('paid', 'refunded')) then 'renewal' else 'new' end,
    'customer', v_uid)
  returning * into v_o;

  perform private.order_event(v_o.id, 'placed', 'The couple placed this order from their dashboard.');
  perform private.order_event(v_o.id, 'confirmation', 'Confirmation #' || v_o.confirmation || ' was generated for this order.');
  return jsonb_build_object('ok', true, 'paid', false, 'order', private.order_brief(v_o));
end;
$$;

create function private.my_publish_state(p_wedding uuid)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  v_w public.weddings;
  v_o public.orders;
begin
  select * into v_w from public.weddings where id = p_wedding;
  if v_w.id is null or not private.can_view_wedding(v_w.id) then
    return null;
  end if;
  select * into v_o from public.orders where wedding_id = v_w.id and status = 'pending';
  return jsonb_build_object(
    'price', private.order_price(), 'currency', 'EGP', 'months', private.order_months(),
    'canPublish', private.wedding_can_go_live(v_w.id),
    'activeUntil', v_w.active_until,
    'turnedOff', v_w.deactivated_at is not null,
    'order', case when v_o.id is null then null else private.order_brief(v_o) end);
end;
$$;

create function private.cancel_my_order(p_order uuid)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_o public.orders;
begin
  select * into v_o from public.orders where id = p_order for update;
  if v_o.id is null or v_o.status <> 'pending'
     or not (v_o.buyer_id = (select auth.uid()) or private.can_edit_wedding(v_o.wedding_id)) then
    return jsonb_build_object('ok', false, 'error', 'This order can''t be cancelled.');
  end if;
  update public.orders set status = 'cancelled', cancelled_at = now(), cancel_reason = 'Cancelled by the couple' where id = v_o.id;
  perform private.order_event(v_o.id, 'cancelled', 'The couple cancelled this order.');
  return jsonb_build_object('ok', true);
end;
$$;

-- ── Staff: list, view, act ─────────────────────────────────────────────────
create function private.admin_list_orders(p_tab text, p_search text, p_limit integer, p_offset integer)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  v_role   public.staff_role := private.require_staff(array['owner', 'admin']::public.staff_role[]);
  v_tab    text := coalesce(p_tab, 'all');
  v_q      text := nullif(btrim(coalesce(p_search, '')), '');
  v_like   text := case when v_q is null then null else private.like_pattern(v_q) end;
  v_num    bigint := case when v_q ~ '^#?[0-9]{1,12}$' then ltrim(v_q, '#')::bigint end;
  v_users  uuid[] := '{}';
  v_hits   uuid[];
  v_limit  integer := least(greatest(coalesce(p_limit, 50), 1), 200);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
  v_counts jsonb;
  v_total  integer;
  v_rows   jsonb;
begin
  -- Search: each kind of match is its own indexed lookup (number, code,
  -- name/phone/reference, customer email, couple), then the ids are merged.
  if v_like is not null then
    select coalesce(array_agg(id), '{}') into v_users
      from (select id from auth.users where lower(email) like v_like limit 1000) e;
    select coalesce(array_agg(id), '{}') into v_hits from (
      select id from public.orders where number = v_num
      union select id from public.orders where confirmation = upper(v_q)
      union select id from public.orders
             where lower(coalesce(customer_name, '') || ' ' || coalesce(customer_phone, '') || ' ' || coalesce(reference, '')) like v_like
      union select id from public.orders where buyer_id = any (v_users)
      union select o.id from public.orders o join public.weddings w on w.id = o.wedding_id
             where lower(w.slug || ' ' || w.partner_one_name || ' ' || w.partner_two_name) like v_like
      limit 5000) h;
  end if;

  -- Tab counts in one pass (the tabs show them like badges).
  select jsonb_build_object(
           'all',       count(*) filter (where o.archived_at is null),
           'pending',   count(*) filter (where o.archived_at is null and o.status = 'pending'),
           'paid',      count(*) filter (where o.archived_at is null and o.status = 'paid'),
           'notLive',   count(*) filter (where o.archived_at is null and o.status = 'paid' and not coalesce(
                          w.status = 'published' and w.deactivated_at is null and (w.active_until is null or w.active_until > now()), false)),
           'refunded',  count(*) filter (where o.archived_at is null and o.status = 'refunded'),
           'cancelled', count(*) filter (where o.archived_at is null and o.status = 'cancelled'),
           'archived',  count(*) filter (where o.archived_at is not null))
    into v_counts
    from public.orders o left join public.weddings w on w.id = o.wedding_id;

  with m as materialized (
    select o.id, o.created_at
      from public.orders o
      left join public.weddings w on w.id = o.wedding_id
     where case v_tab
             when 'archived' then o.archived_at is not null
             when 'pending' then o.archived_at is null and o.status = 'pending'
             when 'paid' then o.archived_at is null and o.status = 'paid'
             when 'notLive' then o.archived_at is null and o.status = 'paid' and not coalesce(
                    w.status = 'published' and w.deactivated_at is null and (w.active_until is null or w.active_until > now()), false)
             when 'refunded' then o.archived_at is null and o.status = 'refunded'
             when 'cancelled' then o.archived_at is null and o.status = 'cancelled'
             else o.archived_at is null
           end
       and (v_q is null or o.id = any (v_hits))
  ), page as (
    select m.id, m.created_at from m order by m.created_at desc, m.id limit v_limit offset v_offset
  )
  select (select count(*) from m),
         coalesce(jsonb_agg(jsonb_build_object(
           'id', o.id, 'number', o.number, 'confirmation', o.confirmation, 'status', o.status,
           'amount', o.amount, 'currency', o.currency, 'method', o.method, 'kind', o.kind, 'source', o.source,
           'createdAt', o.created_at, 'paidAt', o.paid_at, 'tags', to_jsonb(o.tags), 'archived', o.archived_at is not null,
           'customerName', o.customer_name, 'customerEmail', u.email, 'customerPhone', o.customer_phone,
           'weddingId', o.wedding_id, 'slug', w.slug, 'templateId', w.template_id,
           'names', case when w.id is null then null else w.partner_one_name || ' & ' || w.partner_two_name end,
           'live', case
                     when w.id is null then null
                     when w.deactivated_at is not null then 'off'
                     when w.active_until is not null and w.active_until <= now() then 'ended'
                     when w.status = 'published' then 'live'
                     else 'notLive'
                   end
         ) order by pg.created_at desc, pg.id), '[]'::jsonb)
    into v_total, v_rows
    from page pg
    join public.orders o on o.id = pg.id
    left join public.weddings w on w.id = o.wedding_id
    left join auth.users u on u.id = o.buyer_id;

  return jsonb_build_object('total', v_total, 'counts', v_counts, 'rows', v_rows);
end;
$$;

create function private.admin_get_order(p_order uuid)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  v_role public.staff_role := private.require_staff(array['owner', 'admin']::public.staff_role[]);
  v jsonb;
begin
  select jsonb_build_object(
    'order', private.order_brief(o) || jsonb_build_object(
      'reference', o.reference, 'note', o.note, 'source', o.source, 'tags', to_jsonb(o.tags),
      'refundedAt', o.refunded_at, 'cancelledAt', o.cancelled_at, 'cancelReason', o.cancel_reason,
      'archived', o.archived_at is not null, 'recordedBy', uc.email),
    'customer', jsonb_build_object(
      'id', o.buyer_id, 'name', o.customer_name, 'email', ub.email, 'phone', o.customer_phone,
      'orders', (select count(*) from public.orders x where x.buyer_id = o.buyer_id and x.status <> 'cancelled'),
      'nth', (select count(*) from public.orders x where x.buyer_id = o.buyer_id and x.status <> 'cancelled' and x.created_at <= o.created_at)),
    'wedding', case when w.id is null then null else jsonb_build_object(
      'id', w.id, 'slug', w.slug, 'names', w.partner_one_name || ' & ' || w.partner_two_name,
      'templateId', w.template_id, 'status', w.status, 'weddingDate', w.wedding_date,
      'activeUntil', w.active_until, 'deactivatedAt', w.deactivated_at) end,
    'events', coalesce((
      select jsonb_agg(jsonb_build_object(
               'at', e.at, 'kind', e.kind, 'message', e.message,
               'actor', case when e.actor is null then null when e.actor = o.buyer_id then 'Customer' else ua.email end)
             order by e.at desc, e.id desc)
        from public.order_events e left join auth.users ua on ua.id = e.actor
       where e.order_id = o.id), '[]'::jsonb))
    into v
    from public.orders o
    left join public.weddings w on w.id = o.wedding_id
    left join auth.users ub on ub.id = o.buyer_id
    left join auth.users uc on uc.id = o.created_by
   where o.id = p_order;
  return v;
end;
$$;

create function private.admin_mark_paid(p_order uuid, p_amount numeric, p_method text, p_reference text)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_role public.staff_role := private.require_staff(array['owner', 'admin']::public.staff_role[]);
  v_res jsonb;
begin
  if p_method is not null and p_method not in ('cash', 'instapay', 'vodafone_cash', 'bank_transfer', 'card', 'paymob', 'other') then
    return jsonb_build_object('ok', false, 'error', 'Unknown payment method.');
  end if;
  v_res := private.settle_order(p_order, p_amount, p_method, p_reference, null, true);
  if (v_res ->> 'ok')::boolean then
    perform private.audit('order.paid', 'order', p_order::text, jsonb_build_object('amount', p_amount, 'method', p_method, 'reference', p_reference));
  end if;
  return v_res;
end;
$$;

create function private.admin_cancel_order(p_order uuid, p_reason text)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_role   public.staff_role := private.require_staff(array['owner', 'admin']::public.staff_role[]);
  v_reason text := nullif(left(btrim(coalesce(p_reason, '')), 300), '');
begin
  update public.orders set status = 'cancelled', cancelled_at = now(), cancel_reason = v_reason
   where id = p_order and status = 'pending';
  if not found then
    return jsonb_build_object('ok', false, 'error', 'Only orders waiting for payment can be cancelled. Refund paid ones instead.');
  end if;
  perform private.order_event(p_order, 'cancelled', 'Order cancelled' || coalesce(': ' || v_reason, '') || '.');
  perform private.audit('order.cancel', 'order', p_order::text, jsonb_build_object('reason', v_reason));
  return jsonb_build_object('ok', true);
end;
$$;

create function private.admin_order_note(p_order uuid, p_text text)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_role public.staff_role := private.require_staff(array['owner', 'admin']::public.staff_role[]);
  v_text text := btrim(coalesce(p_text, ''));
begin
  if char_length(v_text) not between 1 and 1000 then
    return jsonb_build_object('ok', false, 'error', 'Write a comment of up to 1,000 characters.');
  end if;
  if not exists (select 1 from public.orders where id = p_order) then
    return jsonb_build_object('ok', false, 'error', 'This order no longer exists.');
  end if;
  perform private.order_event(p_order, 'comment', v_text);
  return jsonb_build_object('ok', true);
end;
$$;

create function private.admin_set_order_tags(p_order uuid, p_tags text[])
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_role public.staff_role := private.require_staff(array['owner', 'admin']::public.staff_role[]);
  v_tags text[];
begin
  select coalesce(array_agg(t order by first), '{}') into v_tags
    from (select left(btrim(t), 30) as t, min(ord) as first
            from unnest(coalesce(p_tags, '{}')) with ordinality as x(t, ord)
           where btrim(t) <> ''
           group by left(btrim(t), 30)
           order by min(ord)
           limit 10) d;
  update public.orders set tags = v_tags where id = p_order;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'This order no longer exists.');
  end if;
  perform private.audit('order.tags', 'order', p_order::text, jsonb_build_object('tags', v_tags));
  return jsonb_build_object('ok', true, 'tags', to_jsonb(v_tags));
end;
$$;

create function private.admin_archive_order(p_order uuid, p_archived boolean)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_role public.staff_role := private.require_staff(array['owner', 'admin']::public.staff_role[]);
begin
  update public.orders set archived_at = case when p_archived then coalesce(archived_at, now()) end where id = p_order;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'This order no longer exists.');
  end if;
  perform private.order_event(p_order, case when p_archived then 'archived' else 'unarchived' end,
                              case when p_archived then 'Order archived.' else 'Order moved back from the archive.' end);
  return jsonb_build_object('ok', true);
end;
$$;

-- ── Existing staff actions, now through orders and the timeline ────────────
create or replace function private.admin_record_sale(
  p_wedding uuid, p_amount numeric, p_method text, p_reference text, p_note text, p_months integer, p_publish boolean
)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_role   public.staff_role := private.require_staff(array['owner', 'admin']::public.staff_role[]);
  v_w      public.weddings;
  v_months integer := least(greatest(coalesce(p_months, 3), 0), 36);
  v_order  uuid;
  v_res    jsonb;
begin
  select * into v_w from public.weddings where id = p_wedding for update;
  if v_w.id is null then
    return jsonb_build_object('ok', false, 'error', 'This invitation no longer exists.');
  end if;
  if p_amount is null or p_amount < 0 or p_amount > 1000000 then
    return jsonb_build_object('ok', false, 'error', 'Enter an amount between 0 and 1,000,000.');
  end if;

  -- The couple's open order, if any, is the one being paid.
  select id into v_order from public.orders where wedding_id = v_w.id and status = 'pending' for update;
  if v_order is not null then
    update public.orders set months = v_months where id = v_order;
  else
    insert into public.orders (wedding_id, buyer_id, amount, method, months, status, customer_name, kind, source, created_by)
    values (v_w.id, v_w.owner_id, round(p_amount, 2), p_method, v_months, 'pending',
            (select p.full_name from public.profiles p where p.id = v_w.owner_id),
            case when exists (select 1 from public.orders o where o.wedding_id = v_w.id and o.status in ('paid', 'refunded')) then 'renewal' else 'new' end,
            'staff', (select auth.uid()))
    returning id into v_order;
    perform private.order_event(v_order, 'placed', 'Recorded by staff from the admin.');
  end if;

  v_res := private.settle_order(v_order, p_amount, p_method, p_reference, p_note, p_publish);
  if not (v_res ->> 'ok')::boolean then
    return v_res;
  end if;
  perform private.audit('sale.record', 'wedding', v_w.id::text,
    jsonb_build_object('order', v_order, 'amount', p_amount, 'method', p_method, 'months', v_months, 'activeUntil', v_res -> 'activeUntil', 'published', p_publish));
  return v_res;
end;
$$;

create or replace function private.admin_refund(p_order uuid, p_deactivate boolean)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_role public.staff_role := private.require_staff(array['owner', 'admin']::public.staff_role[]);
  v_o public.orders;
begin
  update public.orders set status = 'refunded', refunded_at = now()
   where id = p_order and status = 'paid'
   returning * into v_o;
  if v_o.id is null then
    return jsonb_build_object('ok', false, 'error', 'That sale was not found or is already refunded.');
  end if;
  if p_deactivate and v_o.wedding_id is not null then
    update public.weddings set deactivated_at = now(), deactivated_reason = 'Refunded' where id = v_o.wedding_id and deactivated_at is null;
  end if;
  perform private.order_event(v_o.id, 'refunded', private.money(v_o.amount, v_o.currency) || ' refunded'
    || case when p_deactivate then ' and the invitation turned off.' else '.' end);
  perform private.audit('sale.refund', 'order', v_o.id::text, jsonb_build_object('wedding', v_o.wedding_id, 'amount', v_o.amount, 'deactivated', p_deactivate));
  return jsonb_build_object('ok', true);
end;
$$;

